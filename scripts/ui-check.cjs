    assert.equal(resumed?.status,'passed',resumed?.summary);assert.equal(calls.length-beforeResume,2);assert.equal(resumed.metrics.usage.calls,2);assert.ok(resumed.metrics.checkpoint.reusedPhases.length>0);
    await page.locator('[data-tab="overview"]').click();
    await page.waitForTimeout(2500);
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.waitForTimeout(200);
    const colors=await page.evaluate(()=>({background:getComputedStyle(document.body).backgroundColor,radius:getComputedStyle(document.querySelector('.panel')).borderRadius,monitor:document.querySelector('#telemetry-content').textContent,active:getComputedStyle(document.querySelector('.nav-button.active')).backgroundColor,headerY:document.querySelector('.global-header').getBoundingClientRect().y}));
    assert.equal(colors.background,'rgb(10, 10, 10)');
    assert.equal(colors.radius,'0px');
    assert.equal(colors.active,'rgb(51, 255, 0)');assert.equal(colors.headerY,0);
    assert.ok(!colors.monitor.includes('遥测暂不可用'));
    await page.screenshot({path:path.join(artifactRoot,'desktop-overview.png'),fullPage:true});
    await page.screenshot({path:path.join(artifactRoot,'desktop-window.png')});
    const state=await page.evaluate(()=>window.audit.invoke('state'));
    assert.ok(state.project.files.some(f=>f.path==='src/auth.js'&&f.status==='read'));
    assert.equal(state.settings.model,'smoke-local-model');
    assert.equal(state.settings.apiKey,undefined);
    assert.equal(calls[0].model,'smoke-local-model');
    assert.deepEqual(errors,[]);
