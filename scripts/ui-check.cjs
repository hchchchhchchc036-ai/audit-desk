    assert.equal(telemetry.context.capacityTokens,1000000);assert.equal(state.settings.contextWindowTokens,1000000);
    assert.equal(typeof telemetry.network.online,'boolean');
    assert.ok(await page.locator('#header-network').isVisible());
    assert.ok(await page.locator('#header-power').isVisible());
    assert.match(await page.locator('#header-time').textContent(),/\d{2}:\d{2}:\d{2}/);
    const previousProjectId=state.project.id;
    await application.close();
    application=await electron.launch({...(process.env.AUDIT_DESK_EXECUTABLE?{executablePath:process.env.AUDIT_DESK_EXECUTABLE,args:[]}:{args:[root]}),env,timeout:30000});
    const restartedPage=await application.firstWindow();await restartedPage.waitForSelector('h1');
    await restartedPage.waitForFunction(()=>document.querySelector('#project-name').textContent==='尚未选择项目');
    const restarted=await restartedPage.evaluate(()=>window.audit.invoke('state'));
