    await page.waitForSelector('h1',{timeout:45000});
    await page.locator('[data-tab="settings"]').click();
    const saveButton=page.locator('#settings-form button[type="submit"]');
    assert.equal(await saveButton.evaluate(node=>!!node.closest('.panel-head')),false,'settings form belongs in panel content');
    for(const state of ['normal','hover','disabled']){
      if(state==='hover')await saveButton.hover();
      if(state==='disabled')await saveButton.evaluate(node=>node.disabled=true);
      const colors=await saveButton.evaluate(node=>({foreground:getComputedStyle(node).color,background:getComputedStyle(node).backgroundColor}));
      assert.equal(colors.foreground,'rgb(10, 10, 10)');
      assert.ok(['rgb(51, 255, 0)','rgb(106, 255, 65)'].includes(colors.background),'primary action has green background');
    }
    await saveButton.evaluate(node=>node.disabled=false);
    const disabledContext=await page.locator('#reset-context').evaluate(node=>({disabled:node.disabled,color:getComputedStyle(node).color,opacity:getComputedStyle(node).opacity}));
    assert.equal(disabledContext.disabled,true);assert.equal(disabledContext.opacity,'1');assert.equal(disabledContext.color,'rgb(132, 153, 123)');
    await page.locator('#model').fill('smoke-local-model');
    await page.locator('#baseUrl').fill(`http://127.0.0.1:${server.address().port}/v1`);
    await page.locator('#contextWindowTokens').selectOption('1000000');
    await page.locator('#settings-form button[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelector('#notification').textContent.includes('已保存'),{},{timeout:30000});
    await page.locator('button').filter({hasText:'测试已保存的连接'}).click();
    await page.waitForFunction(()=>document.querySelector('#notification').textContent.includes('模型连接成功'),{},{timeout:10000});
    await application.evaluate(({dialog},fixture)=>{
      dialog.showOpenDialog=async()=>({canceled:false,filePaths:[fixture]});
    },path.join(root,'.runtime','界面测试 项目'));
    await page.locator('#import-project').click();
    await page.waitForFunction(()=>document.querySelector('#project-name').textContent==='界面测试 项目');
    await page.locator('[data-tab="skills"]').click();
    assert.equal(await page.locator('.skill-card').count(),5,'five real bundled skills');
    await page.locator('button').filter({hasText:'查看 / 编辑内容'}).first().click();
    await page.locator('#skill-dialog').waitFor({state:'visible'});
    assert.ok((await page.locator('#skill-content').inputValue()).includes('name:'));
    await page.locator('#close-dialog').click();
    await page.locator('[data-tab="audit"]').click();
    assert.ok(await page.locator('input[name="scopes"]').count()>1,'module scopes visible');
    await page.locator('[data-tab="test"]').click();
    assert.equal(await page.locator('input[name="generate"]').isChecked(),true,'model generation is enabled by default');
    assert.equal(await page.locator('input[name="testType"][type="checkbox"]').count(),4);
    await page.locator('#select-all-tests').click();assert.equal(await page.locator('input[name="testType"]:checked').count(),4);
    assert.ok(await page.locator('#thresholdMs').isVisible());
    await page.locator('#clear-tests').click();assert.equal(await page.locator('input[name="testType"]:checked').count(),0);
    assert.equal(await page.locator('#thresholdMs').isVisible(),false);
    await page.locator('input[name="testType"][value="unit"]').check();
    await page.locator('input[name="testType"][value="performance"]').check();
    await page.locator('#durationSeconds').fill('10');
    assert.ok(await page.locator('#thresholdMs').isVisible());
    await page.locator('[data-tab="overview"]').click();
    assert.equal(await page.locator('#live-workflow .step').count(),3,'default workflow is retained before a task starts');
    const liveTask=await page.evaluate(()=>window.audit.invoke('task:start',{kind:'test',scopes:['.'],skillIds:[],testType:'unit',generate:false,command:['node','--test','tests/auth.test.js']}));
    let finished;
    const taskDeadline=Date.now()+60000;
    while(Date.now()<taskDeadline){
      finished=await page.evaluate(async id=>(await window.audit.invoke('state')).tasks.find(t=>t.id===id),liveTask.id);
      if(finished&&!['running','queued'].includes(finished.status))break;
      await page.waitForTimeout(250);
    }
    assert.equal(finished.status,'passed',JSON.stringify(finished));
    assert.equal(finished.metrics.executionMode,'local');
    assert.ok(finished.metrics.flowEvents.some(event=>event.tool==='local-process'),'actual local execution is recorded');
    assert.ok(!finished.metrics.flowEvents.some(event=>String(event.tool).toLowerCase().includes('docker')),'default mode never invokes Docker');
    assert.ok(await page.locator('#live-workflow .live-node').count()>0,'workflow switches to actual phase nodes');
    const exportRoot=path.join(artifactRoot,'ui-export');await fs.mkdir(exportRoot,{recursive:true});
    await application.evaluate(({dialog},folder)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[folder]});dialog.showSaveDialog=async()=>({canceled:false,filePath:folder+'\\中文测试报告.docx'});},exportRoot);
    const exported=await page.evaluate(id=>window.audit.invoke('report:export',{id}),liveTask.id);
    assert.equal(exported.format,'docx');
    const zip=require('fflate').unzipSync(await fs.readFile(exported.path));
    const wordXml=Buffer.from(zip['word/document.xml']).toString('utf8');
    assert.ok(wordXml.includes('测试了什么')&&wordXml.includes('正常'),'Word contains Chinese test content and results');
    const evidence=await page.evaluate(id=>window.audit.invoke('report:exportEvidence',{id}),liveTask.id);
    assert.ok((await fs.readFile(path.join(evidence.path,'report.md'),'utf8')).includes('正常'));
    assert.ok((await fs.readFile(path.join(evidence.path,'runner-output.log'),'utf8')).includes('pass'));
    const batch=await page.evaluate(()=>window.audit.invoke('task:start',{kind:'test',scopes:['.'],skillIds:[],testType:'unit',testTypes:['unit','functional'],generate:false,command:['node','--test','tests/auth.test.js']}));
    assert.equal(batch.length,2);assert.deepEqual(batch.map(t=>t.input.testType),['unit','functional']);assert.equal(batch[0].input.contextBinding.contextId,batch[1].input.contextBinding.contextId);
    const batchDeadline=Date.now()+30000;let batchState;
    do{await page.waitForTimeout(100);batchState=await page.evaluate(()=>window.audit.invoke('state'));}while(batchState.tasks.some(t=>batch.some(b=>b.id===t.id)&&['queued','running'].includes(t.status))&&Date.now()<batchDeadline);
    for(const t of batch)assert.equal(batchState.tasks.find(b=>b.id===t.id).status,'passed');
    await page.evaluate(()=>window.audit.invoke('settings:save',{timeoutSeconds:5}));
    const recovering=await page.evaluate(()=>window.audit.invoke('task:start',{kind:'test',scopes:['.'],skillIds:[],testType:'unit',generate:true}));
    let recovered;const recoveryDeadline=Date.now()+30000;
    do{await page.waitForTimeout(100);recovered=await page.evaluate(async id=>(await window.audit.invoke('state')).tasks.find(t=>t.id===id),recovering.id);}while(['queued','running'].includes(recovered.status)&&Date.now()<recoveryDeadline);
    assert.equal(recovered.status,'passed');assert.equal(generatedCalls,2);
    const attempts=recovered.metrics.flowEvents.filter(e=>e.tool==='model-api');assert.equal(attempts.length,2);assert.equal(attempts[0].status,'failed');assert.equal(attempts[1].status,'completed');assert.ok(attempts[1].detail.includes('timeout_seconds=10'));
    const auditTask=await page.evaluate(()=>window.audit.invoke('task:start',{kind:'audit',engine:'security-audit',scopes:['src'],skillIds:[]}));
    let audited;const auditDeadline=Date.now()+30000;
    do{await page.waitForTimeout(100);audited=await page.evaluate(async id=>(await window.audit.invoke('state')).tasks.find(t=>t.id===id),auditTask.id);}while(['queued','running'].includes(audited.status)&&Date.now()<auditDeadline);
    assert.equal(audited.status,'passed',audited.summary);assert.equal(audited.metrics.companionSchemaValidated,true);assert.equal(audited.coverage.reviewed,1);assert.ok(audited.metrics.jobs.some(j=>j.phase==='guided-followup-src/auth.js'&&j.status==='complete'));assert.deepEqual(audited.metrics.workflowGaps,[]);
    pauseCritic=true;
    const interrupted=await page.evaluate(()=>window.audit.invoke('task:start',{kind:'audit',engine:'security-audit',scopes:['src'],skillIds:[]}));
    const interruptDeadline=Date.now()+30000;while(!criticWaiting&&Date.now()<interruptDeadline)await page.waitForTimeout(50);assert.equal(criticWaiting,true);
    await page.evaluate(id=>window.audit.invoke('task:cancel',{id}),interrupted.id);pauseCritic=false;
    await page.locator('[data-tab="audit"]').click();
