    assert.equal(restarted.settings.model,'smoke-local-model');assert.ok(restarted.projects.some(p=>p.id===previousProjectId));
    assert.ok(restarted.tasks.some(t=>t.id===liveTask.id));
    assert.equal(await restartedPage.locator('#live-workflow .step').count(),3);
    await restartedPage.evaluate(async id=>{state=await window.audit.invoke('project:select',{id});render();},previousProjectId);
